"""
Unit tests for WakeWordDetector and WakeWordConfig.
Tests grammar constraint, energy gating, cooldown debounce, pause/resume, and clean release.
"""

import time
from pathlib import Path
import numpy as np
import pytest

from src.audio.wake_word import WakeWordConfig, WakeWordDetector


def test_wake_word_config_defaults():
    cfg = WakeWordConfig()
    assert cfg.phrase == "activate david"
    assert cfg.sample_rate == 16000
    assert cfg.enabled is True
    assert cfg.cooldown_seconds == 2.5
    assert cfg.energy_threshold > 0.0


def test_wake_word_detector_silence_rejection():
    """Silence should be rejected by the RMS energy gate without hitting the recognizer."""
    detector = WakeWordDetector()
    detector.load_model()
    assert detector.is_loaded is True

    # 1 second of complete silence (zeros)
    silent_chunk = np.zeros(16000, dtype=np.int16).tobytes()
    detected = detector.process_audio_chunk(silent_chunk)
    assert detected is False

    detector.unload()
    assert detector.is_loaded is False


def test_wake_word_pause_and_resume():
    """Paused detector should ignore all audio chunks."""
    detector = WakeWordDetector()
    detector.load_model()

    detector.pause()
    assert detector.is_paused is True

    # Feed noise
    noise_chunk = (np.random.randn(4000) * 1000).astype(np.int16).tobytes()
    assert detector.process_audio_chunk(noise_chunk) is False

    detector.resume()
    assert detector.is_paused is False

    detector.unload()


def test_wake_word_detection_with_synthetic_speech():
    """Tests detection of synthesized 'activate david' audio generated by Piper TTS."""
    from src.audio.config import AudioConfig
    from src.audio.tts import PiperTtsEngine

    audio_cfg = AudioConfig()
    tts = PiperTtsEngine(audio_cfg)
    tts.load_voice()

    synth = tts.synthesize("activate david")
    assert synth.audio_data is not None

    # Resample or feed directly at TTS sample rate
    # Vosk model configured for TTS sample rate (22050 Hz)
    cfg = WakeWordConfig(sample_rate=synth.sample_rate)
    detector = WakeWordDetector(cfg)
    detector.load_model()

    pcm = (synth.audio_data * 32767).astype(np.int16).tobytes()

    chunk_size = 4000
    detected = False
    for i in range(0, len(pcm), chunk_size):
        chunk = pcm[i : i + chunk_size]
        if detector.process_audio_chunk(chunk):
            detected = True
            break

    assert detected is True

    # Test cooldown: immediate re-feeding should return False due to debounce
    immediate_second = detector.process_audio_chunk(pcm[:chunk_size])
    assert immediate_second is False

    detector.unload()


